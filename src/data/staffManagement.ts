export const createDefaultWorkingHours = (customHours?: Partial<StaffWorkingDay>): StaffWorkingDay[] => {
  const days: StaffWorkingDay['day'][] = [
    'Monday',
    'Tuesday',
    'Wednesday',
    'Thursday',
    'Friday',
    'Saturday',
    'Sunday',
  ];

  return days.map((day) => ({
    day,
    enabled: day !== 'Sunday',
    startTime: day === 'Saturday' ? '10:00 AM' : '09:00 AM',
    endTime: day === 'Saturday' ? '05:00 PM' : '06:00 PM',
    breakStart: '01:00 PM',
    breakEnd: '02:00 PM',
    ...customHours,
  }));
};

